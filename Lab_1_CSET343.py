# 2. TEXTUAL DATA - CLINICAL NOTE


print("\n" + "=" * 60)
print("2. TEXTUAL DATA - CLINICAL NOTE")
print("=" * 60)

# Sample clinical note
clinical_note = """
Patient reports chest pain during physical activity.
Patient has a history of high blood pressure and high cholesterol.
Heart rate increases during exercise.
Patient denies severe shortness of breath.
Recommended cardiovascular evaluation and regular monitoring.
"""

# Save as text file
with open("patient_note.txt", "w") as file:
    file.write(clinical_note)

# Read text file
with open("patient_note.txt", "r") as file:
    text = file.read()

print("\nClinical Note:")
print(text)

# Convert to lowercase
text_lower = text.lower()

# Extract words
words = re.findall(r'\b[a-z]+\b', text_lower)

print("Total Words:", len(words))
print("Unique Words:", len(set(words)))

# Word frequency
word_frequency = Counter(words)

print("\nMost Common Words:")
for word, count in word_frequency.most_common(10):
    print(word, ":", count)

# Remove basic stopwords
stopwords = {
    "the", "a", "an", "and", "of", "to",
    "is", "has", "during", "with", "for",
    "patient"
}

important_words = [
    word for word in words
    if word not in stopwords
]

print("\nImportant Clinical Terms:")
for word, count in Counter(important_words).most_common(10):
    print(word, ":", count)



# 3. SIGNAL DATA - ECG


print("\n" + "=" * 60)
print("3. SIGNAL DATA - ECG")
print("=" * 60)

# Upload ECG ZIP in Google Colab
from google.colab import files

print("\nUpload your 'ECG DATA.zip' file:")
uploaded = files.upload()

# Get uploaded ZIP filename
zip_file = list(uploaded.keys())[0]

# Extract ZIP
extract_folder = "ecg_data"

with zipfile.ZipFile(zip_file, 'r') as zip_ref:
    zip_ref.extractall(extract_folder)

print("\nECG ZIP extracted successfully!")

# Find 100s ECG record
record_path = None

for root, dirs, file_list in os.walk(extract_folder):

    if "100s.dat" in file_list:
        record_path = os.path.join(root, "100s")
        break

print("ECG Record:", record_path)



# Read ECG Signal


record = wfdb.rdrecord(record_path)

print("\nECG Information:")
print("Sampling Frequency:", record.fs, "Hz")
print("Number of Samples:", record.sig_len)
print("Number of Channels:", record.n_sig)
print("Channel Names:", record.sig_name)
print("Signal Shape:", record.p_signal.shape)



# Read ECG Annotations


annotation = wfdb.rdann(
    record_path,
    "atr"
)

print("\nNumber of Annotations:", len(annotation.sample))
print("First 20 Annotation Symbols:")
print(annotation.symbol[:20])



# Plot ECG - First 10 Seconds


seconds = 10

samples = int(seconds * record.fs)

ecg = record.p_signal[:samples, 0]

time = np.arange(samples) / record.fs

plt.figure(figsize=(15,5))

plt.plot(time, ecg)

plt.xlabel("Time (seconds)")
plt.ylabel("ECG Amplitude")
plt.title("ECG Signal - First 10 Seconds")
plt.grid()

plt.show()



# ECG WITH ANNOTATIONS


plt.figure(figsize=(15,5))

plt.plot(
    time,
    ecg,
    label="ECG Signal"
)

for sample, symbol in zip(
    annotation.sample,
    annotation.symbol
):

    if sample < samples:

        plt.axvline(
            sample / record.fs,
            linestyle="--",
            alpha=0.5
        )

plt.xlabel("Time (seconds)")
plt.ylabel("Amplitude")
plt.title("ECG Signal with Beat Annotations")
plt.grid()

plt.show()



# Calculate Approximate Heart Rate


beat_samples = annotation.sample[
    annotation.sample < samples
]

rr_intervals = np.diff(beat_samples) / record.fs

average_rr = np.mean(rr_intervals)

heart_rate = 60 / average_rr

print("\nECG Analysis:")
print("Detected Beats:", len(beat_samples))
print(
    "Average RR Interval:",
    round(average_rr, 3),
    "seconds"
)
print(
    "Approximate Heart Rate:",
    round(heart_rate, 2),
    "BPM"
)



