# HEART FAILURE CLINICAL RECORDS DATASET - COMPLETE CLEANING



# 1. IMPORT LIBRARIES


import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.preprocessing import MinMaxScaler


# 2. LOAD DATASET


# Read dataset
file_path = "/content/heart_failure_clinical_records_dataset.csv"

df = pd.read_csv(file_path)

print("Dataset Loaded Successfully!")


# 3. DISPLAY FIRST 5 ROWS


print("\nFirst 5 Rows:")
display(df.head())


# 4. SUMMARIZE DATASET


print("\nNumber of Rows:", df.shape[0])
print("Number of Columns:", df.shape[1])

print("\nColumn Names:")
print(df.columns.tolist())

print("\nData Types:")
print(df.dtypes)

print("\nMissing Values:")
print(df.isnull().sum())

# Dataset information
print("\nDataset Information:")
df.info()


# 5. VISUALIZE MISSING VALUES


plt.figure(figsize=(12, 6))
sns.heatmap(df.isnull(), cbar=False, cmap="viridis")
plt.title("Missing Values Heatmap")
plt.xlabel("Features")
plt.ylabel("Records")
plt.show()


# 6. IDENTIFY NUMERICAL AND CATEGORICAL FEATURES


numerical_features = df.select_dtypes(include=np.number).columns.tolist()

# Binary/categorical columns in Heart Failure dataset
categorical_features = [
    'anaemia',
    'diabetes',
    'high_blood_pressure',
    'sex',
    'smoking'
]

# Keep only columns that actually exist
categorical_features = [
    col for col in categorical_features
    if col in df.columns
]

# Remove categorical columns from numerical list
numerical_features = [
    col for col in numerical_features
    if col not in categorical_features
]

print("\nNumerical Features:")
print(numerical_features)

print("\nCategorical Features:")
print(categorical_features)


# 7. PLOT DISTRIBUTIONS BEFORE CLEANING


# Histograms
for column in numerical_features:
    plt.figure(figsize=(6, 4))
    sns.histplot(df[column], kde=True)
    plt.title(f"Distribution of {column} - Before Cleaning")
    plt.xlabel(column)
    plt.show()

# Specific boxplots for important numerical features
important_features = ['age', 'ejection_fraction', 'serum_creatinine']

for column in important_features:
    if column in df.columns:
        plt.figure(figsize=(7, 3))
        sns.boxplot(x=df[column])
        plt.title(f"Boxplot of {column} - Before Cleaning")
        plt.show()


# 8. SUMMARY STATISTICS BEFORE CLEANING


print("\nSummary Statistics BEFORE Cleaning:")
before_cleaning_stats = df[numerical_features].agg(
    ['mean', 'median', 'std']
)

display(before_cleaning_stats)


# 9. CREATE A COPY FOR CLEANING


df_clean = df.copy()


# 10. CORRECT INVALID OR INCONSISTENT VALUES


# Age cannot be negative
if 'age' in df_clean.columns:
    df_clean.loc[df_clean['age'] < 0, 'age'] = np.nan

# Ejection fraction cannot be negative
if 'ejection_fraction' in df_clean.columns:
    df_clean.loc[df_clean['ejection_fraction'] < 0,
                 'ejection_fraction'] = np.nan

# Serum creatinine cannot be negative
if 'serum_creatinine' in df_clean.columns:
    df_clean.loc[df_clean['serum_creatinine'] < 0,
                 'serum_creatinine'] = np.nan

# Platelets cannot be negative
if 'platelets' in df_clean.columns:
    df_clean.loc[df_clean['platelets'] < 0,
                 'platelets'] = np.nan

# Serum sodium cannot be negative
if 'serum_sodium' in df_clean.columns:
    df_clean.loc[df_clean['serum_sodium'] < 0,
                 'serum_sodium'] = np.nan

# CPK cannot be negative
if 'creatinine_phosphokinase' in df_clean.columns:
    df_clean.loc[df_clean['creatinine_phosphokinase'] < 0,
                 'creatinine_phosphokinase'] = np.nan

print("\nInvalid negative values corrected.")


# 11. IMPUTE MISSING NUMERICAL VALUES


for column in numerical_features:
    if df_clean[column].isnull().sum() > 0:

        # Use median because it is more robust to outliers
        median_value = df_clean[column].median()

        df_clean[column] = df_clean[column].fillna(median_value)

print("\nNumerical missing values imputed using median.")


# 12. IMPUTE MISSING CATEGORICAL VALUES


for column in categorical_features:
    if df_clean[column].isnull().sum() > 0:

        # Fill with most frequent value (mode)
        mode_value = df_clean[column].mode()[0]

        df_clean[column] = df_clean[column].fillna(mode_value)

print("Categorical missing values imputed using mode.")


# 13. REMOVE OUTLIERS USING IQR METHOD


# Features where IQR-based outlier removal will be applied
outlier_features = numerical_features.copy()

initial_rows = df_clean.shape[0]

for column in outlier_features:

    Q1 = df_clean[column].quantile(0.25)
    Q3 = df_clean[column].quantile(0.75)

    IQR = Q3 - Q1

    lower_bound = Q1 - 1.5 * IQR
    upper_bound = Q3 + 1.5 * IQR

    df_clean = df_clean[
        (df_clean[column] >= lower_bound) &
        (df_clean[column] <= upper_bound)
    ]

final_rows = df_clean.shape[0]

print("\nOutlier Removal Completed")
print("Rows Before Removing Outliers:", initial_rows)
print("Rows After Removing Outliers:", final_rows)
print("Outliers Removed:", initial_rows - final_rows)


# 14. FEATURE ENGINEERING - AGE GROUP


if 'age' in df_clean.columns:

    df_clean['age_group'] = pd.cut(
        df_clean['age'],
        bins=[0, 40, 60, np.inf],
        labels=['<40', '40-60', '>60'],
        right=False
    )

print("\nAge Group Feature Created")


# 15. FEATURE ENGINEERING - RISK SCORE


# Normalize ejection fraction and serum creatinine
if ('ejection_fraction' in df_clean.columns and
        'serum_creatinine' in df_clean.columns):

    ef_min = df_clean['ejection_fraction'].min()
    ef_max = df_clean['ejection_fraction'].max()

    sc_min = df_clean['serum_creatinine'].min()
    sc_max = df_clean['serum_creatinine'].max()

    # Avoid division by zero
    df_clean['ejection_fraction_normalized'] = (
        (df_clean['ejection_fraction'] - ef_min) /
        (ef_max - ef_min)
    )

    df_clean['serum_creatinine_normalized'] = (
        (df_clean['serum_creatinine'] - sc_min) /
        (sc_max - sc_min)
    )

    # Risk score based on normalized product
    df_clean['risk_score'] = (
        df_clean['ejection_fraction_normalized'] *
        df_clean['serum_creatinine_normalized']
    )

print("\nRisk Score Feature Created")


# 16. ENCODE CATEGORICAL VARIABLES


# One-hot encode age_group
if 'age_group' in df_clean.columns:

    df_clean = pd.get_dummies(
        df_clean,
        columns=['age_group'],
        drop_first=False,
        dtype=int
    )

# Binary columns are already encoded as 0 and 1
# We ensure categorical columns have integer format
for column in categorical_features:
    if column in df_clean.columns:
        df_clean[column] = df_clean[column].astype(int)

print("\nCategorical Variables Encoded")


# 17. NORMALIZE NUMERICAL FEATURES USING MINMAXSCALER


# Create separate list of original numerical features
features_to_scale = [
    'age',
    'creatinine_phosphokinase',
    'ejection_fraction',
    'platelets',
    'serum_creatinine',
    'serum_sodium',
    'time'
]

# Keep only existing columns
features_to_scale = [
    col for col in features_to_scale
    if col in df_clean.columns
]

# Create MinMaxScaler
scaler = MinMaxScaler()

# Normalize between 0 and 1
df_clean[features_to_scale] = scaler.fit_transform(
    df_clean[features_to_scale]
)

print("\nNumerical Features Normalized Successfully")


# 18. COMPUTE SUMMARY STATISTICS AFTER CLEANING


# Numerical columns after cleaning
cleaned_numerical_features = df_clean.select_dtypes(
    include=np.number
).columns.tolist()

print("\nSummary Statistics AFTER Cleaning:")

after_cleaning_stats = df_clean[
    cleaned_numerical_features
].agg(['mean', 'median', 'std'])

display(after_cleaning_stats)


# 19. COMPARE BEFORE AND AFTER CLEANING


print("\nBEFORE CLEANING:")
display(before_cleaning_stats)

print("\nAFTER CLEANING:")
display(after_cleaning_stats)


# 20. VALIDATE CLEANING WITH HISTOGRAMS


for column in features_to_scale:

    plt.figure(figsize=(6, 4))

    sns.histplot(
        df_clean[column],
        kde=True
    )

    plt.title(
        f"Distribution of {column} - After Cleaning and Normalization"
    )

    plt.xlabel(column)
    plt.ylabel("Frequency")

    plt.show()


# 21. VALIDATE CLEANING WITH BOXPLOTS


for column in features_to_scale:

    plt.figure(figsize=(7, 3))

    sns.boxplot(x=df_clean[column])

    plt.title(
        f"Boxplot of {column} - After Cleaning"
    )

    plt.show()


# 22. FINAL MISSING VALUES CHECK


print("\nFINAL MISSING VALUES:")
final_missing = df_clean.isnull().sum()

print(final_missing)

print("\nTotal Missing Values Remaining:",
      final_missing.sum())


# 23. FINAL DATASET INFORMATION


print("\nFINAL CLEANED DATASET SHAPE:")
print(df_clean.shape)

print("\nFINAL DATASET:")
display(df_clean.head())


# 24. SAVE CLEANED DATASET


df_clean.to_csv(
    "heart_failure_cleaned_dataset.csv",
    index=False
)

print(
    "\nCleaned dataset saved successfully as "
    "'heart_failure_cleaned_dataset.csv'"
)

