# D. SIGNAL DATA - MIT-BIH ECG

print(" D. SIGNAL DATA ")

# Download ECG record
record_name = "100"

wfdb.dl_database(
    "mitdb",
    dl_dir="/content/mitdb",
    records=[record_name]
)

record = wfdb.rdrecord("/content/mitdb/100")

ecg = record.p_signal[:,0]
fs = record.fs

print("Sampling frequency:", fs)
print("Number of samples:", len(ecg))

# Plot raw ECG
plt.figure(figsize=(12,4))
plt.plot(ecg[:2000])
plt.title("Raw ECG Signal")
plt.xlabel("Samples")
plt.ylabel("Amplitude")
plt.show()

# Noise removal - Bandpass filter
b,a = signal.butter(
    4,
    [0.5/(fs/2),40/(fs/2)],
    btype="band"
)

filtered = signal.filtfilt(b,a,ecg)

# Normalize
filtered = (filtered-filtered.mean())/filtered.std()

plt.figure(figsize=(12,4))
plt.plot(filtered[:2000])
plt.title("Filtered and Normalized ECG")
plt.xlabel("Samples")
plt.ylabel("Amplitude")
plt.show()

# R-peak detection
peaks,_ = signal.find_peaks(
    filtered,
    distance=int(0.25*fs),
    prominence=0.5
)

print("Detected R-peaks:", len(peaks))

# Signal windowing
windows = []

for p in peaks[:100]:
    if p-50 >= 0 and p+100 < len(filtered):
        windows.append(filtered[p-50:p+100])

windows = np.array(windows)

print("ECG window shape:", windows.shape)