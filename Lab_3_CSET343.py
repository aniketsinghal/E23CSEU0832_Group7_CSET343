# A. TABULAR DATA - PIMA DIABETES

print("A. TABULAR DATA ")

url = "https://raw.githubusercontent.com/jbrownlee/Datasets/master/pima-indians-diabetes.data.csv"

cols = ["Pregnancies","Glucose","BloodPressure","SkinThickness",
        "Insulin","BMI","DiabetesPedigreeFunction","Age","Outcome"]

df = pd.read_csv(url, names=cols)

print("Shape:", df.shape)
display(df.head())
display(df.describe())

# Healthcare-specific missing values
missing_cols = ["Glucose","BloodPressure","SkinThickness","Insulin","BMI"]

df[missing_cols] = df[missing_cols].replace(0, np.nan)
df[missing_cols] = df[missing_cols].fillna(df[missing_cols].median())

print("\nMissing values:")
print(df.isnull().sum())

# EDA
sns.countplot(x="Outcome", data=df)
plt.title("Diabetes Class Distribution")
plt.show()

sns.heatmap(df.corr(), annot=True, cmap="coolwarm")
plt.title("Correlation Heatmap")
plt.show()

# Feature engineering
df["BMI_Category"] = pd.cut(
    df["BMI"],
    bins=[0,18.5,25,30,100],
    labels=["Underweight","Normal","Overweight","Obese"]
)

# -------- Hypothesis Test --------
# H0: Glucose means are equal
g0 = df[df.Outcome == 0]["Glucose"]
g1 = df[df.Outcome == 1]["Glucose"]

t,p = ttest_ind(g0,g1,equal_var=False)

print("\nHypothesis Test:")
print("t =", round(t,3), "p =", p)
print("Result:", "Significant difference" if p < 0.05 else "No significant difference")

# -------- Chi-Square Test --------
table = pd.crosstab(df["BMI_Category"], df["Outcome"])
chi,p,dof,expected = chi2_contingency(table)

print("\nChi-Square Test:")
print("Chi2 =", round(chi,3), "p =", p)
print("Result:", "Associated" if p < 0.05 else "Not associated")

# -------- ANOVA --------
groups = [
    x["Glucose"].values
    for _,x in df.groupby("BMI_Category", observed=True)
]

F,p = f_oneway(*groups)

print("\nANOVA:")
print("F =", round(F,3), "p =", p)
print("Result:", "Significant" if p < 0.05 else "Not significant")

