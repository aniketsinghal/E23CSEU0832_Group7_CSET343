# 1. IMPORT LIBRARIES


import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from ucimlrepo import fetch_ucirepo
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    classification_report,
    confusion_matrix,
    ConfusionMatrixDisplay,
    roc_curve,
    roc_auc_score
)

import warnings
warnings.filterwarnings("ignore")

# TASK 1: DATA ACQUISITION AND EXPLORATION
print("TASK 1: DATA ACQUISITION AND EXPLORATION")

# 2. DOWNLOAD AND LOAD DATASET
breast_cancer = fetch_ucirepo(id=17)

X = breast_cancer.data.features
y = breast_cancer.data.targets

# Combine features and target
df = pd.concat([X, y], axis=1)

print("\nDataset Shape:", df.shape)

print("\nFirst 5 rows:")
display(df.head())

# 3. BASIC INFORMATION

print("\nDataset Information:")
df.info()

print("\nColumn Names:")
print(df.columns.tolist())

# 4. SUMMARY STATISTICS


print("\n" + "=" * 50)
print("SUMMARY STATISTICS")
print("=" * 50)

print("\nMean:")
display(X.mean())
print("\nMedian:")
display(X.median())
print("\nStandard Deviation:")
display(X.std())

print("\nComplete Statistical Summary:")
display(X.describe().T)

# 5. MISSING VALUES

print("\n" + "=" * 50)
print("MISSING VALUES")
print("=" * 50)

missing_values = df.isnull().sum()

display(missing_values)

print("Total Missing Values:", df.isnull().sum().sum())

# Handle missing values if any
if df.isnull().sum().sum() > 0:
    df = df.dropna()
    print("Missing values removed.")
else:
    print("No missing values found.")

# 6. DUPLICATES

print("\n" + "=" * 50)
print("DUPLICATES")
print("=" * 50)

duplicates = df.duplicated().sum()

print("Number of duplicate rows:", duplicates)

if duplicates > 0:
    df = df.drop_duplicates()
    print("Duplicate rows removed.")
else:
    print("No duplicate rows found.")

# 7. OUTLIER DETECTION USING IQR
print("\n" + "=" * 50)
print("OUTLIER DETECTION")
print("=" * 50)

# Remove target and ID for numerical analysis
X_outlier = df.drop(columns=["Diagnosis", "ID"], errors="ignore")

Q1 = X_outlier.quantile(0.25)
Q3 = X_outlier.quantile(0.75)

IQR = Q3 - Q1

lower_bound = Q1 - 1.5 * IQR
upper_bound = Q3 + 1.5 * IQR

outlier_count = ((X_outlier < lower_bound) |
                 (X_outlier > upper_bound)).sum()

outlier_summary = pd.DataFrame({
    "Q1": Q1,
    "Q3": Q3,
    "IQR": IQR,
    "Lower Bound": lower_bound,
    "Upper Bound": upper_bound,
    "Outlier Count": outlier_count
})

display(outlier_summary)

print("\nNote: Outliers are not removed because extreme medical")
print("measurements may represent genuine observations.")

# 8. HISTOGRAMS
print("\n" + "=" * 50)
print("HISTOGRAMS")
print("=" * 50)

X_outlier.hist(
    figsize=(20, 20),
    bins=20
)

plt.suptitle(
    "Distribution of Breast Cancer Features",
    fontsize=18
)

plt.tight_layout()
plt.show()
# 9. BOXPLOTS

plt.figure(figsize=(20, 8))

sns.boxplot(data=X_outlier)

plt.xticks(rotation=90)
plt.title("Box Plots of Features")
plt.xlabel("Features")
plt.ylabel("Values")
plt.show()
# 10. CLASS DISTRIBUTION

print("\n" + "=" * 50)
print("CLASS DISTRIBUTION")
print("=" * 50)
print(df["Diagnosis"].value_counts())
print("\nClass Distribution (%):")
print(
    df["Diagnosis"]
    .value_counts(normalize=True)
    .mul(100)
    .round(2)
)
plt.figure(figsize=(7, 5))

sns.countplot(
    data=df,
    x="Diagnosis"
)
plt.title("Class Distribution")
plt.xlabel("Diagnosis (B = Benign, M = Malignant)")
plt.ylabel("Number of Samples")

plt.show()
# 11. CORRELATION HEATMAP

print("\n" + "=" * 50)
print("CORRELATION HEATMAP")
print("=" * 50)

plt.figure(figsize=(18, 14))

correlation_matrix = X_outlier.corr()

sns.heatmap(
    correlation_matrix,
    cmap="coolwarm",
    center=0
)

plt.title("Correlation Heatmap")
plt.show()
# TASK 2: DATA PREPROCESSING

print("\n" + "=" * 70)
print("TASK 2: DATA PREPROCESSING")

# 12. SEPARATE FEATURES AND TARGET

X = df.drop(
    columns=["Diagnosis", "ID"],
    errors="ignore"
)

y = df["Diagnosis"]
# 13. ENCODE TARGET VARIABLE

# B = 0 (Benign)
# M = 1 (Malignant)

y = y.map({
    "B": 0,
    "M": 1
})

print("\nEncoded Target:")
print(y.value_counts())

# 14. TRAIN-TEST SPLIT

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("\nTraining Set Shape:", X_train.shape)
print("Testing Set Shape:", X_test.shape)

print("\nTraining Class Distribution:")
print(y_train.value_counts(normalize=True))

print("\nTesting Class Distribution:")
print(y_test.value_counts(normalize=True))

# 15. STANDARDIZATION

scaler = StandardScaler()

X_train_scaled = scaler.fit_transform(X_train)

X_test_scaled = scaler.transform(X_test)

print("\nFeatures standardized successfully.")

# TASK 3: MODEL TRAINING AND EVALUATION

print("\n" + "=" * 70)
print("TASK 3: LOGISTIC REGRESSION MODEL")

# 16. TRAIN LOGISTIC REGRESSION

model = LogisticRegression(
    max_iter=1000,
    random_state=42
)

model.fit(
    X_train_scaled,
    y_train
)

print("\nLogistic Regression model trained successfully.")

# 17. PREDICTIONS

y_pred = model.predict(X_test_scaled)

# Probability of malignant class
y_prob = model.predict_proba(X_test_scaled)[:, 1]

# 18. ACCURACY

accuracy = accuracy_score(
    y_test,
    y_pred
)

print("\n" + "=" * 50)
print("ACCURACY")
print("=" * 50)

print("Accuracy:", round(accuracy, 4))
print("Accuracy (%):", round(accuracy * 100, 2), "%")



# 19. PRECISION, RECALL, F1-SCORE


print("\n" + "=" * 50)
print("PRECISION, RECALL AND F1-SCORE")
print("=" * 50)

print(
    classification_report(
        y_test,
        y_pred,
        target_names=["Benign", "Malignant"]
    )
)



# 20. CONFUSION MATRIX


cm = confusion_matrix(
    y_test,
    y_pred
)

print("\n" + "=" * 50)
print("CONFUSION MATRIX")
print("=" * 50)

print(cm)

disp = ConfusionMatrixDisplay(
    confusion_matrix=cm,
    display_labels=["Benign", "Malignant"]
)

disp.plot()

plt.title("Confusion Matrix - Logistic Regression")

plt.show()



# 21. ROC CURVE AND AUC


fpr, tpr, thresholds = roc_curve(
    y_test,
    y_prob
)

auc_score = roc_auc_score(
    y_test,
    y_prob
)

print("\n" + "=" * 50)
print("ROC-AUC")
print("=" * 50)

print("AUC Score:", round(auc_score, 4))


plt.figure(figsize=(8, 6))

plt.plot(
    fpr,
    tpr,
    label=f"Logistic Regression (AUC = {auc_score:.3f})"
)

plt.plot(
    [0, 1],
    [0, 1],
    linestyle="--",
    label="Random Classifier"
)

plt.xlabel("False Positive Rate")
plt.ylabel("True Positive Rate")

plt.title("ROC Curve")

plt.legend()

plt.show()



# FINAL RESULTS TABLE


print("\n" + "=" * 70)
print("FINAL RESULTS")


report = classification_report(
    y_test,
    y_pred,
    target_names=["Benign", "Malignant"],
    output_dict=True
)

results = pd.DataFrame({
    "Class": ["Benign", "Malignant"],
    "Precision": [
        report["Benign"]["precision"],
        report["Malignant"]["precision"]
    ],
    "Recall": [
        report["Benign"]["recall"],
        report["Malignant"]["recall"]
    ],
    "F1-Score": [
        report["Benign"]["f1-score"],
        report["Malignant"]["f1-score"]
    ]
})

display(results)

print("\nOverall Accuracy:", round(accuracy, 4))
print("ROC-AUC Score:", round(auc_score, 4))

# INTERPRETATION

print("\n" + "=" * 70)
print("INTERPRETATION")